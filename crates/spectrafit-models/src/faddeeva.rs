//!
//! This module is a Rust port of the Faddeeva Package by Steven G. Johnson
//! (Massachusetts Institute of Technology, 2012; <http://ab-initio.mit.edu/Faddeeva>),
//! taken from the copy SciPy vendors as `scipy.special.wofz`
//! (SciPy 1.18.1, `subprojects/xsf/include/xsf/faddeeva.h`). It ports `w(z)`
//! (only the default `relerr = 0` branch, i.e. machine precision), the real
//! scaled complementary error function `erfcx(x)` and `w_im(x) = Im[w(x)]` for
