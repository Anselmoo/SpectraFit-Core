//! Deviations from the C++ source: complex numbers are `(re, im)` tuples; the
//! `relerr` argument is fixed at machine precision; `w_im(−x)` is written as
//! `−w_im(x)` (the C++ duplicates an odd-symmetric branch); and the second
//! summation loop of the `x ≥ 10` branch is omitted because it is unreachable
//! (that branch needs `n0 = round(x/a) ≥ 19`, while the two-sided loop
//! converges after about a dozen terms). Accuracy against a 50-digit mpmath
//! reference is pinned by the tests below.
//!
//! **Not part of the port.** The Faddeeva Package has no derivative.
//! [`w_with_derivative`] and the three functions it dispatches to
//! (`w_prime_continued_fraction`, `w_prime_sums`, `w_prime_two_sided`) are
//! original code of this crate (spectrafit-core, #106): term-by-term
//! derivatives of the ported representations, derived in their doc comments.

